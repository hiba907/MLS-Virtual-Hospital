"""
patient_chart_pdf.py - prescription PDF for the MLS Virtual Hospital Patient Chart.

SIMULATION DOCUMENT. Every page carries a permanent diagonal "SIMULATED" watermark and a banner stating that the
patient is simulated and the document is not a valid prescription. The hospital stamp states "SIMULATION - TRAINING
ONLY". The signature block shows the prescriber's typed name as an electronic signature made inside the simulation;
no handwritten signature image is used, so the document cannot pass as a real signed prescription.

Optional: put a hospital logo at static/mls_logo.png and/or a stamp image at static/mls_stamp.png (next to app.py) to
use them instead of the drawn defaults. The watermark and banner are always added.
"""
import datetime as _dt
import os
import unicodedata

from fpdf import FPDF

HOSPITAL = "MLS Virtual Hospital"
BANNER = "SIMULATED PATIENT - TRAINING USE ONLY - NOT A VALID PRESCRIPTION - DO NOT DISPENSE"
_MAP = {"–": "-", "—": "-", "→": "->", "←": "<-", "₂": "2", "≥": ">=", "≤": "<=", "’": "'", "‘": "'",
        "“": '"', "”": '"', "…": "...", "•": "*", "×": "x", "µ": "u", "°": " deg", " ": " "}
_HERE = os.path.dirname(os.path.abspath(__file__))


def _t(s):
    """Make text safe for the built-in PDF fonts (Latin-1 only)."""
    s = "" if s is None else str(s)
    for k, v in _MAP.items():
        s = s.replace(k, v)
    out = []
    for ch in s:
        try:
            ch.encode("latin-1")
            out.append(ch)
            continue
        except UnicodeEncodeError:
            pass
        base = "".join(c for c in unicodedata.normalize("NFKD", ch) if not unicodedata.combining(c))
        out.append(base if base and all(ord(c) < 256 for c in base) else "?")
    return "".join(out)


def _img(name):
    p = os.path.join(_HERE, "static", name)
    return p if os.path.exists(p) else None


class _Doc(FPDF):
    def header(self):
        # watermark first so everything else prints over it
        with self.local_context(fill_opacity=0.10):
            self.set_font("Helvetica", "B", 90)
            self.set_text_color(120, 120, 120)
            with self.rotation(45, x=105, y=150):
                self.text(28, 170, "SIMULATED")
        self.set_text_color(0, 0, 0)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "I", 7.5)
        self.set_text_color(90, 90, 90)
        self.multi_cell(0, 4, _t(f"Generated by {HOSPITAL} on {_dt.date.today().isoformat()}. Educational simulation "
                                 "document: no clinical or legal validity. Never use for real patients."),
                        align="C")


def _stamp(pdf, cx, cy, r=19):
    path = _img("mls_stamp.png")
    if path:
        pdf.image(path, x=cx - r, y=cy - r, w=2 * r, h=2 * r)
        return
    with pdf.rotation(-14, x=cx, y=cy):
        pdf.set_draw_color(21, 67, 150)
        pdf.set_text_color(21, 67, 150)
        pdf.set_line_width(0.9)
        pdf.ellipse(cx - r, cy - r, 2 * r, 2 * r)
        pdf.set_line_width(0.3)
        pdf.ellipse(cx - r + 2, cy - r + 2, 2 * (r - 2), 2 * (r - 2))
        pdf.set_font("Helvetica", "B", 8.5)
        pdf.set_xy(cx - r, cy - 9)
        pdf.cell(2 * r, 4, "MLS VIRTUAL", align="C")
        pdf.set_xy(cx - r, cy - 5)
        pdf.cell(2 * r, 4, "HOSPITAL", align="C")
        pdf.set_font("Helvetica", "B", 7)
        pdf.set_xy(cx - r, cy + 1)
        pdf.cell(2 * r, 4, "SIMULATION", align="C")
        pdf.set_xy(cx - r, cy + 5)
        pdf.cell(2 * r, 4, "TRAINING ONLY", align="C")
    pdf.set_draw_color(0, 0, 0)
    pdf.set_text_color(0, 0, 0)
    pdf.set_line_width(0.2)


def _section(pdf, title):
    pdf.ln(2)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(21, 67, 150)
    pdf.cell(0, 6, _t(title.upper()), new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(180, 190, 210)
    pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
    pdf.ln(1.5)
    pdf.set_text_color(0, 0, 0)


def _para(pdf, text, size=10, style=""):
    pdf.set_font("Helvetica", style, size)
    pdf.multi_cell(0, 5, _t(text), align="L", new_x="LMARGIN", new_y="NEXT")


def prescription_pdf(pat, visit, day=None, reviewer=None):
    """Return PDF bytes. pat/visit are the chart's dicts; reviewer = faculty display name (or None)."""
    d = visit.get("data") or {}
    pdf = _Doc(orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=22)
    pdf.set_margins(15, 15, 15)
    pdf.add_page()

    # ---- header
    logo = _img("mls_logo.png")
    if logo:
        pdf.image(logo, x=15, y=12, h=16)
    pdf.set_xy(15 if not logo else 34, 12)
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(21, 67, 150)
    pdf.cell(0, 9, _t(HOSPITAL), new_x="LMARGIN", new_y="NEXT")
    pdf.set_x(15 if not logo else 34)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(70, 70, 70)
    pdf.cell(0, 5, "Simulation-based clinical training platform - Prescription", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)

    # ---- red banner
    pdf.set_fill_color(253, 232, 232)
    pdf.set_draw_color(198, 40, 40)
    pdf.set_text_color(160, 20, 20)
    pdf.set_font("Helvetica", "B", 9)
    pdf.multi_cell(0, 6, _t(BANNER), border=1, align="C", fill=True, new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(0, 0, 0)
    pdf.set_text_color(0, 0, 0)
    pdf.ln(2)

    # ---- patient block
    _section(pdf, "Patient (simulated)")
    age = pat.get("age_years")
    try:
        age_s = f"{float(age):g} y"
    except (TypeError, ValueError):
        age_s = "-"
    _para(pdf, f"Name: {pat.get('alias', '-')}    Age: {age_s}    Sex: {pat.get('sex') or '-'}", 11, "B")
    dayp = f"    Hospital day: {day}" if day else ""
    _para(pdf, f"Date: {visit.get('visit_date', '-')}    Visit: {visit.get('visit_type') or '-'}{dayp}", 10)
    if pat.get("title"):
        _para(pdf, f"Case: {pat['title']}", 10)
    al = pat.get("allergies") or []
    if al:
        pdf.set_text_color(170, 20, 20)
        _para(pdf, "ALLERGIES: " + "; ".join(
            a.get("substance", "") + (f" ({a['reaction']})" if a.get("reaction") else "") +
            (f" - {a['severity']}" if a.get("severity") else "") for a in al), 10, "B")
        pdf.set_text_color(0, 0, 0)
    else:
        _para(pdf, "Allergies: none recorded", 10)

    if d.get("diagnosis"):
        _section(pdf, "Diagnosis / assessment")
        _para(pdf, d["diagnosis"])

    # ---- Rx table
    _section(pdf, "Rx")
    rows = [r for r in d.get("prescriptions", []) if r.get("drug")]
    widths = [50, 24, 18, 28, 24, 36]
    heads = ["Drug", "Dose", "Route", "Frequency", "Duration", "Notes"]
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_fill_color(228, 234, 247)
    for w, h in zip(widths, heads):
        pdf.cell(w, 7, h, border=1, fill=True)
    pdf.ln()
    pdf.set_font("Helvetica", "", 9)
    if not rows:
        pdf.cell(sum(widths), 7, "No medications prescribed at this visit.", border=1, new_x="LMARGIN", new_y="NEXT")
    for r in rows:
        vals = [r.get("drug", ""), r.get("dose", ""), r.get("route", ""),
                r.get("frequency") or r.get("freq", ""), r.get("duration", ""), r.get("notes", "")]
        y0 = pdf.get_y()
        lines = max(len(pdf.multi_cell(w, 5, _t(v), dry_run=True, output="LINES")) or 1 for w, v in zip(widths, vals))
        h = max(7, 5 * lines + 2)
        if y0 + h > pdf.h - 28:
            pdf.add_page()
            y0 = pdf.get_y()
        x = pdf.l_margin
        for w, v in zip(widths, vals):
            pdf.rect(x, y0, w, h)
            pdf.set_xy(x + 0.5, y0 + 1)
            pdf.multi_cell(w - 1, 5, _t(v), align="L", new_x="RIGHT", new_y="TOP")
            x += w
        pdf.set_xy(pdf.l_margin, y0 + h)

    if d.get("plan"):
        _section(pdf, "Plan")
        _para(pdf, d["plan"])
    if d.get("followup_date") or d.get("followup_instructions") or d.get("followup_note"):
        _section(pdf, "Follow-up")
        _para(pdf, " - ".join(x for x in (d.get("followup_date"), d.get("followup_instructions") or
                                         d.get("followup_note")) if x))

    # ---- signatures and stamp (keep together on one page)
    if pdf.get_y() > pdf.h - 80:
        pdf.add_page()
    pdf.ln(6)
    y = pdf.get_y()
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_xy(15, y)
    pdf.cell(80, 5, "Prescriber (electronic signature, simulation)")
    pdf.set_font("Times", "I", 17)
    pdf.set_xy(15, y + 7)
    pdf.cell(80, 9, _t(visit.get("author_name") or "-"))
    pdf.line(15, y + 17, 95, y + 17)
    pdf.set_font("Helvetica", "", 8)
    pdf.set_xy(15, y + 18)
    pdf.cell(80, 4, _t(f"Signed in simulation on {str(visit.get('created_at') or visit.get('visit_date'))[:10]}"))

    pdf.set_font("Helvetica", "B", 9)
    pdf.set_xy(15, y + 27)
    pdf.cell(80, 5, "Faculty review")
    pdf.set_font("Times", "I", 14)
    pdf.set_xy(15, y + 33)
    pdf.cell(80, 8, _t(reviewer) if reviewer else "")
    pdf.line(15, y + 41, 95, y + 41)
    pdf.set_font("Helvetica", "", 8)
    pdf.set_xy(15, y + 42)
    pdf.cell(80, 4, "Reviewed by faculty" if reviewer else "Not yet reviewed by faculty")

    _stamp(pdf, 155, y + 22)
    return bytes(pdf.output())
