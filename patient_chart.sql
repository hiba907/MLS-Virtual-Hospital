-- patient_chart.sql  -  Patient Chart / Daily Rounds for the MLS Virtual Hospital
-- Run this ONCE in Supabase  ->  SQL Editor  ->  New query  ->  paste ALL of it  ->  Run.
-- (If the editor adds a lone ")" at the very end, delete it before pressing Run.)
--
-- SIMULATED PATIENTS ONLY. These tables deliberately have no columns for phone number, national ID,
-- date of birth, address or photo. Row Level Security is switched on; the app reads and writes with the
-- service_role key kept in Streamlit Secrets, so the public (anon) key can read nothing here.

create table if not exists vh_pc_patients (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  owner_email   text        not null,
  owner_name    text,
  shared        boolean     not null default false,   -- true = faculty class patient, visible to all students
  archived      boolean     not null default false,
  alias         text        not null,                 -- fictional name, e.g. "Mr A (virtual)"
  age_years     numeric,
  sex           text,
  blood_group   text,
  title         text,                                  -- short case title
  admitted_on   date,                                  -- Day 1 of the simulated stay
  brief         text,                                  -- presenting history / admission note
  allergies     jsonb       not null default '[]'::jsonb,
  chronic       jsonb       not null default '[]'::jsonb,
  drug_history  jsonb       not null default '[]'::jsonb,
  case_ref      text                                   -- Case Library id if started from a library case
);

create table if not exists vh_pc_visits (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  patient_id    bigint      not null references vh_pc_patients(id) on delete cascade,
  author_email  text        not null,
  author_name   text,
  visit_date    date        not null,
  visit_type    text,
  data          jsonb       not null default '{}'::jsonb   -- SOAP, vitals, ROS, prescriptions, plan, follow-up
);

create table if not exists vh_pc_labs (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  patient_id    bigint      not null references vh_pc_patients(id) on delete cascade,
  author_email  text        not null,
  author_name   text,
  lab_date      date        not null,
  panel         text,
  results       jsonb       not null default '[]'::jsonb   -- [{name,value,unit,low,high}] (range = what the user typed)
);

create table if not exists vh_pc_feedback (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  patient_id    bigint      not null references vh_pc_patients(id) on delete cascade,
  visit_id      bigint      not null references vh_pc_visits(id)   on delete cascade,
  author_email  text        not null,
  author_name   text,
  text          text        not null
);

create index if not exists vh_pc_patients_owner on vh_pc_patients(owner_email);
create index if not exists vh_pc_visits_patient on vh_pc_visits(patient_id, visit_date);
create index if not exists vh_pc_labs_patient   on vh_pc_labs(patient_id, lab_date);
create index if not exists vh_pc_fb_visit       on vh_pc_feedback(visit_id);

alter table vh_pc_patients enable row level security;
alter table vh_pc_visits   enable row level security;
alter table vh_pc_labs     enable row level security;
alter table vh_pc_feedback enable row level security;
