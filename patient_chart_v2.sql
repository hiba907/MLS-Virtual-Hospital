-- patient_chart_v2.sql  -  second part of the Patient Chart (run AFTER patient_chart.sql)
-- Adds: full history (surgical / family / social / obstetric / paediatric), hospital-stay episodes,
--       investigations with attached files.
-- Run ONCE in Supabase -> SQL Editor -> New query -> paste ALL -> Run.
-- (If the editor adds a lone ")" at the very end, delete it before pressing Run.)
--
-- Simulated patients only. RLS is switched on; the app uses the service_role key from Streamlit Secrets,
-- so the public (anon) key can read nothing here.

alter table vh_pc_patients add column if not exists history jsonb not null default '{}'::jsonb;

create table if not exists vh_pc_hospitalisations (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz not null default now(),
  patient_id      bigint      not null references vh_pc_patients(id) on delete cascade,
  author_email    text        not null,
  author_name     text,
  admit_date      date        not null,
  discharge_date  date,
  data            jsonb       not null default '{}'::jsonb
);

create table if not exists vh_pc_investigations (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz not null default now(),
  patient_id      bigint      not null references vh_pc_patients(id) on delete cascade,
  author_email    text        not null,
  author_name     text,
  inv_date        date        not null,
  kind            text        not null,
  label           text        not null,
  notes           text,
  lab_values      jsonb       not null default '[]'::jsonb,
  visit_id        bigint      references vh_pc_visits(id) on delete set null,
  file            jsonb                                   -- {name, mime, size_kb} when a file is attached
);

create table if not exists vh_pc_files (
  id               bigint generated by default as identity primary key,
  created_at       timestamptz not null default now(),
  patient_id       bigint      not null references vh_pc_patients(id) on delete cascade,
  investigation_id bigint      not null references vh_pc_investigations(id) on delete cascade,
  author_email     text        not null,
  file_name        text,
  mime             text,
  size_kb          numeric,
  b64              text        not null                   -- images are re-encoded (metadata stripped); PDFs as uploaded
);

create index if not exists vh_pc_hosp_patient on vh_pc_hospitalisations(patient_id, admit_date);
create index if not exists vh_pc_inv_patient  on vh_pc_investigations(patient_id, inv_date);
create index if not exists vh_pc_files_inv    on vh_pc_files(investigation_id);

alter table vh_pc_hospitalisations enable row level security;
alter table vh_pc_investigations   enable row level security;
alter table vh_pc_files            enable row level security;
